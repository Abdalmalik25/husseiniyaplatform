for (const file of process.argv.slice(2)) {
  const c = fs.readFileSync(file, "utf8");
  const lines = c.split(NL);
  let fileCount = 0;
  lines.forEach((l, i) => {
    for (const t of TOKENS) {
      if (l.includes(t)) {
        console.log(`${file}:${i + 1}: [${t}] ${l.trim().substring(0, 100)}`);
        fileCount++;
        break;
      }
    }
  });
  console.log(`=== ${file}: ${fileCount} corrupt lines ===`);
  total += fileCount;
}
