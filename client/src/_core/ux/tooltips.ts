/* --------------------------------------------------------------------------
 * Selection helpers - deterministic tie-break (priority desc, title asc).
 * ------------------------------------------------------------------------ */

function compareTitles(a: string, b: string): number {
  if (a < b) return -1;
  if (a > b) return 1;
  return 0;
}

function pickBest(candidates: TooltipEntry[]): TooltipEntry | null {
  if (candidates.length === 0) return null;
  return [...candidates].sort(
    (a, b) => b.priority - a.priority || compareTitles(a.title, b.title)
  )[0];
}

/**
 * Best-priority tooltip for a (topic, field?) pair, or null when nothing
 * matches. With a field, the field-specific entry wins; otherwise it falls
 * back to the topic's general (field-less) entry.
 */
export function tooltipFor(topic: string, field?: string): TooltipEntry | null {
  const exact = TOOLTIPS.filter(
    entry =>
      entry.topic === topic &&
      (field === undefined ? entry.field === undefined : entry.field === field)
  );
  if (exact.length > 0) return pickBest(exact);
  if (field !== undefined) return tooltipFor(topic);
  return null;
}

/**
 * Ordered guidance bullets for a screen. Empty state => first-time "add your
 * first X" steps; otherwise short how-to tips. `hasExamples` appends a
 * concrete sample to the empty-state steps when the topic defines one.
 */
export function guideFor(
  topic: string,
  empty: boolean,
  hasExamples?: boolean
): string[] {
  const guide = GUIDES[topic] ?? DEFAULT_GUIDE;
  if (!empty) return [...guide.how];
  const bullets = [...guide.first];
  if (hasExamples && guide.example) bullets.push(guide.example);
  return bullets;
}

/**
 * Best tooltip per topic (deduplicated), flattened and sorted by priority
 * descending then title ascending - fully deterministic.
 */
export function tooltipsForScreen(topics: string[]): TooltipEntry[] {
  const seen = new Set<string>();
  const tips: TooltipEntry[] = [];
  for (const topic of topics) {
    if (seen.has(topic)) continue;
    seen.add(topic);
    const tip = tooltipFor(topic);
    if (tip) tips.push(tip);
  }
  return tips.sort(
    (a, b) => b.priority - a.priority || compareTitles(a.title, b.title)
  );
}
