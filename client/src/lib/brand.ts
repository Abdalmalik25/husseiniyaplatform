export type Brand = typeof brand;

/** Build a wa.me deep link with pre-filled Arabic text. */
export function whatsappLink(text: string, phone: string = brand.contact.whatsapp): string {
  return `https://wa.me/${phone}?text=${encodeURIComponent(text)}`;
}

/** رابط طلب استشارة هندسية — يوجّه مباشرة لفريق الهندسة والمساحة */
export function engineeringConsultLink(service: string): string {
  const text = `السلام عليكم مؤسسة الحسينية، أودّ الاستفسار عن الخدمة الهندسية: ${service}`;
  return whatsappLink(text, brand.contact.whatsapp2);
}

